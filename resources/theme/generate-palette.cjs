// Generates the theme-aware Tailwind palette. Run from the project root after
// changing a ramp:   node resources/theme/generate-palette.cjs
//   resources/theme/tailwind-colors.json  (read by tailwind.config.js and partials/tailwind)
//   public/css/spacechip-palette.css      (loaded by partials/head-assets and the admin layout)
// Every shade becomes `rgb(var(--tw-<name>-<shade>) / <alpha-value>)`; dark mode mirrors the ramp
// (50<->950, 100<->900, ... 500 stays) so existing light-mode classes read correctly on dark surfaces.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../..');
const tw = require(path.join(root, 'node_modules/tailwindcss/colors.js'));

const PALETTES = ['slate', 'gray', 'zinc', 'neutral', 'stone', 'red', 'orange', 'amber', 'yellow', 'lime', 'green',
    'emerald', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose'];
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];

// Brand ramp built around #1f7a1f (600). The old coral, teal and brand palettes all point here.
const ACCENT = { 50: '#f0f8f0', 100: '#dcefdc', 200: '#b9dfb9', 300: '#8cc98c', 400: '#57ad57', 500: '#2f8f2f',
    600: '#1f7a1f', 700: '#196419', 800: '#154f15', 900: '#113f11', 950: '#0a240a' };

const rgb = (hex) => {
    const h = hex.replace('#', '');
    return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
};

const ramps = Object.fromEntries(PALETTES.map((p) => [p, tw[p]]));
// The brand grays are true neutrals: blue-tinted slate/gray/zinc and warm stone all resolve to neutral.
['slate', 'gray', 'zinc', 'stone'].forEach((p) => { ramps[p] = tw.neutral; });
ramps.accent = ACCENT;

const colors = {};
let light = '';
let dark = '';
for (const [name, ramp] of Object.entries(ramps)) {
    colors[name] = {};
    SHADES.forEach((s, i) => {
        colors[name][s] = `rgb(var(--tw-${name}-${s}) / <alpha-value>)`;
        light += `--tw-${name}-${s}:${rgb(ramp[s])};`;
        dark += `--tw-${name}-${s}:${rgb(ramp[SHADES[SHADES.length - 1 - i]])};`;
    });
    colors[name].DEFAULT = colors[name]['500'];
}
colors.coral = colors.accent;
colors.teal = colors.accent;
colors.brand = { coral: colors.accent['600'], teal: colors.accent['700'] };

// Semantic tokens (values live in spacechip-theme.css).
const token = (v) => `rgb(var(--${v}-rgb) / <alpha-value>)`;
Object.assign(colors, {
    bg: { DEFAULT: token('bg'), subtle: token('bg-subtle') },
    surface: { DEFAULT: token('surface'), 2: token('surface-2'), 3: token('surface-3') },
    border: { DEFAULT: token('border'), strong: token('border-strong') },
    text: token('text'),
    muted: token('muted'),
    faint: token('faint'),
    ink: token('ink'),
    paper: token('surface'),
    'on-accent': token('on-accent'),
    success: { DEFAULT: token('success'), soft: 'var(--success-soft)' },
    warning: { DEFAULT: token('warning'), soft: 'var(--warning-soft)' },
    danger: { DEFAULT: token('danger'), soft: 'var(--danger-soft)', solid: token('danger-solid') },
    info: { DEFAULT: token('info'), soft: 'var(--info-soft)' },
});
// accent keeps its ramp and gains the semantic names used by the new theme.
Object.assign(colors.accent, {
    DEFAULT: token('accent'),
    fill: token('accent-fill'),
    'fill-hover': token('accent-fill-hover'),
    text: token('accent-text'),
    strong: token('accent-strong'),
    soft: 'var(--accent-soft)',
});

const outDir = path.join(root, 'resources/theme');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'tailwind-colors.json'), JSON.stringify(colors));
fs.writeFileSync(path.join(root, 'public/css/spacechip-palette.css'),
    `/* Generated by resources/theme/generate-palette.cjs: Tailwind ramps as RGB channels, mirrored in dark mode. */\n` +
    `html:root{${light}}\nhtml.dark{${dark}}\n`);
console.log('ok', Object.keys(colors).length, 'colour groups');

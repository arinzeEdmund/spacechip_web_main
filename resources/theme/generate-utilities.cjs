// Plain-CSS fallback for the theme's Tailwind colour utilities (bg-surface, text-muted, ring-border…).
// Tailwind generates the same rules when tailwind.config.js is loaded; this file guarantees the colours
// even when the config isn't (stale dev server, CDN without config). It loads before Tailwind, which then
// overrides with identical values.
//   node resources/theme/generate-utilities.cjs     -> public/css/spacechip-utilities.css
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../..');

const NAMES = {
    'bg': 'var(--bg)', 'bg-subtle': 'var(--bg-subtle)',
    'surface': 'var(--surface)', 'surface-2': 'var(--surface-2)', 'surface-3': 'var(--surface-3)',
    'border': 'var(--border)', 'border-strong': 'var(--border-strong)',
    'text': 'var(--text)', 'muted': 'var(--muted)', 'faint': 'var(--faint)', 'ink': 'rgb(var(--ink-rgb))',
    'on-accent': 'var(--on-accent)',
    'accent': 'var(--accent)', 'accent-fill': 'var(--accent-fill)', 'accent-fill-hover': 'var(--accent-fill-hover)',
    'accent-text': 'var(--accent-text)', 'accent-strong': 'var(--accent-strong)', 'accent-soft': 'var(--accent-soft)',
    'success': 'var(--success)', 'success-soft': 'var(--success-soft)',
    'warning': 'var(--warning)', 'warning-soft': 'var(--warning-soft)',
    'danger': 'var(--danger)', 'danger-soft': 'var(--danger-soft)', 'danger-solid': 'var(--danger-solid)',
    'info': 'var(--info)', 'info-soft': 'var(--info-soft)',
};
const PROPS = { bg: 'background-color', text: 'color', border: 'border-color', ring: '--tw-ring-color', fill: 'fill', stroke: 'stroke', divide: 'border-color' };
const VARIANTS = {
    '': (s) => s,
    'hover:': (s) => `${s}:hover`,
    'focus:': (s) => `${s}:focus`,
    'focus-visible:': (s) => `${s}:focus-visible`,
    'disabled:': (s) => `${s}:disabled`,
    'placeholder:': (s) => `${s}::placeholder`,
    'group-hover:': (s) => `.group:hover ${s}`,
    'peer-checked:': (s) => `.peer:checked ~ ${s}`,
    'peer-focus-visible:': (s) => `.peer:focus-visible ~ ${s}`,
};
const ORDER = Object.keys(VARIANTS);

const esc = (c) => c.replace(/([^\w-])/g, '\\$1');
const names = Object.keys(NAMES).sort((a, b) => b.length - a.length).map((n) => n.replace(/-/g, '\\-'));
const re = new RegExp(`^((?:hover:|focus:|focus-visible:|disabled:|placeholder:|group-hover:|peer-checked:|peer-focus-visible:)?)(bg|text|border|ring|fill|stroke|divide)-(${names.join('|')})(?:\\/(\\d{1,3}|\\[\\.\\d+\\]))?$`);

function walk(dir, out = []) {
    for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, f.name);
        if (f.isDirectory()) walk(p, out);
        else if (f.name.endsWith('.php')) out.push(p);
    }
    return out;
}

const seen = new Map();
for (const file of walk(path.join(root, 'resources/views'))) {
    const src = fs.readFileSync(file, 'utf8');
    for (const tok of src.match(/[A-Za-z0-9:_\/.\-\[\]]+/g) || []) {
        const m = re.exec(tok);
        if (m && !seen.has(tok)) seen.set(tok, m);
    }
}

const buckets = Object.fromEntries(ORDER.map((v) => [v, []]));
for (const [tok, m] of seen) {
    const [, variant, prefix, name, alpha] = m;
    let value = NAMES[name];
    if (alpha) {
        const pct = alpha.startsWith('[') ? Math.round(parseFloat(alpha.slice(1, -1)) * 100) : Number(alpha);
        value = `color-mix(in srgb, ${value} ${pct}%, transparent)`;
    }
    const sel = VARIANTS[variant](`.${esc(tok)}`);
    const target = prefix === 'divide' ? `${sel} > :not([hidden]) ~ :not([hidden])` : sel;
    buckets[variant].push(`${target}{${PROPS[prefix]}:${value}}`);
}

const css = `/* Generated by resources/theme/generate-utilities.cjs: plain-CSS fallback for theme colour utilities. */\n`
    + ORDER.flatMap((v) => buckets[v].sort()).join('\n') + '\n';
fs.writeFileSync(path.join(root, 'public/css/spacechip-utilities.css'), css);
console.log('utilities:', seen.size, 'rules');
